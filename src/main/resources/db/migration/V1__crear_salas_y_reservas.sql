CREATE TABLE salas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(100) NOT NULL,
    capacidad  INTEGER      NOT NULL,
    CONSTRAINT uk_salas_nombre UNIQUE (nombre),
    CONSTRAINT ck_salas_capacidad CHECK (capacidad > 0)
);

CREATE TABLE reservas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id      BIGINT       NOT NULL,
    responsable  VARCHAR(100) NOT NULL,
    inicio       TIMESTAMP    NOT NULL,
    fin          TIMESTAMP    NOT NULL,
    estado       VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_reservas_sala FOREIGN KEY (sala_id) REFERENCES salas (id),
    CONSTRAINT ck_reservas_intervalo CHECK (fin > inicio),
    CONSTRAINT ck_reservas_estado CHECK (estado IN ('ACTIVA', 'CANCELADA'))
);

-- Búsqueda de solapamientos y filtros por sala/fecha
CREATE INDEX ix_reservas_sala_inicio ON reservas (sala_id, inicio, fin);
